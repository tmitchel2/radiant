public enum DockArea
{
    /// <summary>The start side (the left, reading left to right).</summary>
    Left,

    /// <summary>The end side.</summary>
    Right,

    /// <summary>Along the bottom, under the centre.</summary>
    Bottom,

    /// <summary>The middle, taking the rest.</summary>
    Center,
}
