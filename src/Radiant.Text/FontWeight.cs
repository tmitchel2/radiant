namespace Radiant.Text;

/// <summary>Common font weights, on the CSS / OpenType 1–1000 scale.</summary>
public static class FontWeight
{
    /// <summary>100.</summary>
    public const float Thin = 100;

    /// <summary>300.</summary>
    public const float Light = 300;

    /// <summary>400: body text.</summary>
    public const float Regular = 400;

    /// <summary>500: labels and titles.</summary>
    public const float Medium = 500;

    /// <summary>600: headings.</summary>
    public const float SemiBold = 600;

    /// <summary>700.</summary>
    public const float Bold = 700;

    /// <summary>900.</summary>
    public const float Black = 900;
}
